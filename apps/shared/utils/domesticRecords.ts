// AgeCategory → テーブルの対応表は1箇所のみ (CLAUDE.md: 同一のドメイン対応表を
// 2箇所にハードコードするな)。呼び出し側・他の getter がこれを再度書く必要はない。
const TABLE_BY_CATEGORY: Readonly<Record<AgeCategory, Readonly<Record<string, number>>>> = {
  elementary: ELEMENTARY_RECORD_TABLE,
  juniorHigh: JUNIOR_HIGH_RECORD_TABLE,
  highSchool: HIGH_SCHOOL_RECORD_TABLE,
  university: UNIVERSITY_RECORD_TABLE,
  general: JAPAN_RECORD_TABLE,
};

/**
 * 指定した年齢区分の国内記録タイム (秒) を取得する。
 * 存在しない組合せ (リレー種目、学童長水路の女子1500m 等) は null を返す。
 */
export function getDomesticRecordTime(
  category: AgeCategory,
  poolType: PoolType,
  gender: Gender,
  styleKey: StyleTranslationKey,
  distance: number,
): number | null {
  const table = TABLE_BY_CATEGORY[category];
  const key = `${poolType}_${gender}_${styleKey}_${distance}`;
  const baseTime = table[key];
  return baseTime === undefined ? null : baseTime;
}

