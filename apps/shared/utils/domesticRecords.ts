export type AgeCategory = "elementary" | "juniorHigh" | "highSchool" | "university" | "general";

/**
 * ベストタイム表の比較指標。WAポイント(既存/世界記録基準) / 日本記録ポイント(nr) / 年齢別ポイント(age)。
 * web/mobile の profile・member-detail の BestTimesTable 4箇所で共有する唯一の定義元
 * (CLAUDE.md: 同一のドメイン対応表を2箇所にハードコードするな)。
 *
 * 制約: この型は waPoints.ts からは参照しないこと (waPoints.ts → domesticRecords.ts の
 * import は既に無いが、domesticRecords.ts → waPoints.ts の一方向依存が既にあるため、
 * 逆方向に参照すると循環 import になる)。
 */
export type CompareMetric = "wa" | "nr" | "age";

/** 年少 → 年長の順。UI のセレクト選択肢順序としても使う。 */
