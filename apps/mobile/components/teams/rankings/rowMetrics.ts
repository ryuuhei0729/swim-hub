// =============================================================================
// rowMetrics - ランキングカード1行の寸法 (フォルダ内共有)
// =============================================================================
//
// `RankingList.tsx` (個人種目) と `RelayRankingList.tsx` (リレー) は同じカード
// レイアウト「1行目: 順位バッジ + 名前/種目 + タイム / 2行目: 大会名 + 日付」を
// 使うため、寸法をここ1箇所に置く。
//
// 2行目の左インデントは 38 という即値ではなく **バッジ幅 + 1行目の gap の和**
// として導出する。片方だけ変えると1行目の名前と2行目の大会名の開始位置が
// 静かにズレるため (見た目だけの破綻はテストでも気づきにくい)。
//
// バレル (`./index.ts`) からは export しない。フォルダ内部品なので外から
// 参照する経路を作らない。

/** 順位バッジの最小幅。3桁順位ではバッジ側が横に伸びる (pill) */
export const RANK_BADGE_WIDTH = 28;

/** 1行目 (バッジ / 名前・種目 / タイム) の要素間 gap */
export const ROW_TOP_LINE_GAP = 10;

/**
 * 2行目 (大会名 / 日付) の左インデント。
 * バッジ幅 + 1行目の gap = 1行目の名前・種目の開始位置に一致させる。
 */
export const ROW_BOTTOM_LINE_INDENT = RANK_BADGE_WIDTH + ROW_TOP_LINE_GAP;
